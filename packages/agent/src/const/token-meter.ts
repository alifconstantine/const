/**
 * Token meter and context pressure estimator adapted from DeepSeek Harness (@deepseek-ai/dsh-token-meter).
 * Provides deterministic, replay-safe token metering, provider usage normalization,
 * context pressure projection, and context breakdown.
 */

/** Fixed character-to-token heuristic divisor. */
export const CHARS_PER_TOKEN = 4;

/** Structural overhead tokens per block for JSON tags and delimiter framing. */
export const BLOCK_OVERHEAD = 4;

/** Role-field framing overhead added to every priced message. */
export const ROLE_OVERHEAD = 4;

/**
 * Normalized token usage from provider response.
 * Handles OpenAI, Anthropic, Gemini, DeepSeek, and Pi-AI wire schemas.
 */
export interface NormalizedTokenUsage {
  /** Uncached prompt / input tokens billed by provider. */
  inputTokens: number;
  /** Output / completion tokens generated by model. */
  outputTokens: number;
  /** Total prompt plus output tokens. */
  totalTokens: number;
  /** Tokens read from provider prompt cache (cache hit). */
  cacheReadTokens?: number;
  /** Tokens written to provider prompt cache (cache creation). */
  cacheWriteTokens?: number;
  /** Reasoning / thinking tokens (subset already included in outputTokens). */
  reasoningTokens?: number;
}

/**
 * Cumulative provider token usage across a complete session or task.
 */
export interface TokenUsageProjection {
  uncachedInputTokens: number;
  outputTokens: number;
  cacheReadTokens: number;
  cacheWriteTokens: number;
  totalTokens: number;
  reasoningTokens: number;
}

/**
 * Context pressure projection for the current conversation state.
 */
export interface ContextPressureProjection {
  /** Provider-reported prompt size of the most recent request (input + cache read/write). */
  pressureTokens?: number;
  /** Projected tokens required for the NEXT request's prompt including surface deltas. */
  projectedTokens?: number;
  /** Total context window capacity of the active model. */
  contextWindow?: number;
}

/**
 * Heuristic composition of the context prompt.
 * What the prompt is made of (composition breakdown, not provider billing).
 */
export interface ContextBreakdownProjection {
  /** Heuristic tokens of the active system prompt. */
  systemTokens: number;
  /** Heuristic tokens of the active tool schemas. */
  toolsTokens: number;
  /** Heuristic tokens of conversation messages (user + assistant + tools). */
  messageTokens: number;
  /** Total heuristic prompt tokens (system + tools + messages). */
  totalHeuristicTokens: number;
}

/**
 * User-facing context occupancy metrics.
 */
export interface ContextOccupancy {
  /** Occupancy percentage (0 to 100). */
  percent: number;
  /** Tokens currently used. */
  usedTokens: number;
  /** Total context window capacity. */
  contextWindow: number;
  /** Remaining context capacity. */
  availableTokens: number;
}

/**
 * Check if a value is a valid non-negative integer count.
 */
function isCount(value: unknown): value is number {
  return typeof value === "number" && Number.isSafeInteger(value) && value >= 0;
}

/**
 * Parse and normalize provider usage across various provider wire formats:
 * - OpenAI / DeepSeek: { prompt_tokens, completion_tokens, total_tokens, prompt_tokens_details: { cached_tokens }, completion_tokens_details: { reasoning_tokens } }
 * - DeepSeek API direct: { prompt_cache_hit_tokens, prompt_cache_miss_tokens }
 * - Anthropic API: { input_tokens, output_tokens, cache_read_input_tokens, cache_creation_input_tokens }
 * - Pi-AI: { input, output, totalTokens, cacheRead, cacheWrite, reasoning }
 */
export function parseProviderUsage(raw: any): NormalizedTokenUsage | undefined {
  if (!raw || typeof raw !== "object") return undefined;

  // Extract input/prompt tokens
  let inputTokens =
    Number(
      raw.inputTokens ??
        raw.input_tokens ??
        raw.promptTokens ??
        raw.prompt_tokens ??
        raw.input ??
        0
    ) || 0;

  // DeepSeek direct cache hit/miss format
  const dsCacheHit = Number(raw.prompt_cache_hit_tokens ?? 0);
  const dsCacheMiss = Number(raw.prompt_cache_miss_tokens ?? 0);
  if (dsCacheHit > 0 || dsCacheMiss > 0) {
    if (!raw.prompt_tokens && !raw.input_tokens) {
      inputTokens = dsCacheMiss;
    }
  }

  // Extract output/completion tokens
  const outputTokens =
    Number(
      raw.outputTokens ??
        raw.output_tokens ??
        raw.completionTokens ??
        raw.completion_tokens ??
        raw.output ??
        0
    ) || 0;

  // Extract cache read tokens
  let cacheReadTokens: number | undefined;
  if (isCount(raw.cacheReadTokens)) {
    cacheReadTokens = raw.cacheReadTokens;
  } else if (isCount(raw.cache_read_input_tokens)) {
    cacheReadTokens = raw.cache_read_input_tokens;
  } else if (isCount(raw.cacheRead)) {
    cacheReadTokens = raw.cacheRead;
  } else if (isCount(raw.prompt_tokens_details?.cached_tokens)) {
    cacheReadTokens = raw.prompt_tokens_details.cached_tokens;
  } else if (dsCacheHit > 0) {
    cacheReadTokens = dsCacheHit;
  }

  // Extract cache write tokens (Anthropic / OpenRouter prompt caching creation)
  let cacheWriteTokens: number | undefined;
  if (isCount(raw.cacheWriteTokens)) {
    cacheWriteTokens = raw.cacheWriteTokens;
  } else if (isCount(raw.cache_creation_input_tokens)) {
    cacheWriteTokens = raw.cache_creation_input_tokens;
  } else if (isCount(raw.cacheWrite)) {
    cacheWriteTokens = raw.cacheWrite;
  } else if (isCount(raw.prompt_tokens_details?.cache_write_tokens)) {
    cacheWriteTokens = raw.prompt_tokens_details.cache_write_tokens;
  } else if (isCount(raw.input_tokens_details?.cache_write_tokens)) {
    cacheWriteTokens = raw.input_tokens_details.cache_write_tokens;
  }

  // Extract reasoning tokens
  let reasoningTokens: number | undefined;
  if (isCount(raw.reasoningTokens)) {
    reasoningTokens = raw.reasoningTokens;
  } else if (isCount(raw.reasoning)) {
    reasoningTokens = raw.reasoning;
  } else if (isCount(raw.completion_tokens_details?.reasoning_tokens)) {
    reasoningTokens = raw.completion_tokens_details.reasoning_tokens;
  } else if (isCount(raw.output_tokens_details?.reasoning_tokens)) {
    reasoningTokens = raw.output_tokens_details.reasoning_tokens;
  }

  // OpenAI-style prompt counts already include cache reads/writes. Anthropic
  // and Pi-AI report uncached input separately. Keep the normalized contract
  // identical for every provider before accumulating or calculating cache hit.
  if (raw.prompt_tokens !== undefined || raw.promptTokens !== undefined ||
      (raw.input_tokens !== undefined && raw.input_tokens_details !== undefined)) {
    cacheReadTokens ??= isCount(raw.input_tokens_details?.cached_tokens)
      ? raw.input_tokens_details.cached_tokens : undefined;
    inputTokens = Math.max(0, inputTokens - (cacheReadTokens ?? 0) - (cacheWriteTokens ?? 0));
  }

  // Determine total tokens
  let totalTokens =
    Number(raw.totalTokens ?? raw.total_tokens) ||
    inputTokens + outputTokens + (cacheReadTokens ?? 0) + (cacheWriteTokens ?? 0);

  if (totalTokens <= 0 && inputTokens <= 0 && outputTokens <= 0) {
    return undefined;
  }

  return {
    inputTokens: Math.max(0, Math.round(inputTokens)),
    outputTokens: Math.max(0, Math.round(outputTokens)),
    totalTokens: Math.max(0, Math.round(totalTokens)),
    ...(cacheReadTokens !== undefined && cacheReadTokens > 0
      ? { cacheReadTokens: Math.round(cacheReadTokens) }
      : {}),
    ...(cacheWriteTokens !== undefined && cacheWriteTokens > 0
      ? { cacheWriteTokens: Math.round(cacheWriteTokens) }
      : {}),
    ...(reasoningTokens !== undefined && reasoningTokens > 0
      ? { reasoningTokens: Math.round(reasoningTokens) }
      : {}),
  };
}

/**
 * Estimate token count for plain text under fixed density heuristic.
 */
export function estimateTextTokens(text: string): number {
  if (!text) return 0;
  return Math.max(1, Math.ceil(text.length / CHARS_PER_TOKEN));
}

/**
 * Estimate token count for tool schemas.
 */
export function estimateToolsTokens(tools?: readonly any[]): number {
  if (!tools || tools.length === 0) return 0;
  try {
    const raw = JSON.stringify(tools);
    return Math.ceil(raw.length / CHARS_PER_TOKEN) + BLOCK_OVERHEAD;
  } catch {
    return tools.length * 85;
  }
}

/** Backwards compatibility alias for estimateToolsTokens */
export const estimateToolSchemasTokens = estimateToolsTokens;

/**
 * Estimate token count for a system prompt.
 */
export function estimateSystemPromptTokens(systemPrompt?: string): number {
  if (!systemPrompt || systemPrompt.trim().length === 0) return 0;
  return Math.ceil(systemPrompt.length / CHARS_PER_TOKEN) + ROLE_OVERHEAD;
}

/**
 * Estimate token count for arbitrary content blocks (text, thinking, tool calls, attachments).
 */
export function estimateContentBlocks(content: any): number {
  if (!content) return 0;

  if (typeof content === "string") {
    return estimateTextTokens(content);
  }

  if (Array.isArray(content)) {
    let tokens = 0;
    for (const block of content) {
      if (!block) continue;
      if (typeof block === "string") {
        tokens += estimateTextTokens(block);
      } else if (typeof block === "object") {
        if (block.type === "text" && typeof block.text === "string") {
          tokens += Math.ceil(block.text.length / CHARS_PER_TOKEN) + BLOCK_OVERHEAD;
        } else if (block.type === "reasoning" && typeof block.text === "string") {
          tokens += Math.ceil(block.text.length / CHARS_PER_TOKEN) + BLOCK_OVERHEAD;
        } else if (block.type === "image" || block.type === "image_url") {
          // Standard provider image base cost heuristic (~1600 tokens per full image)
          tokens += 1600;
        } else if (block.type === "tool-call" || block.type === "function") {
          const nameLen = block.name?.length || block.function?.name?.length || 0;
          const argsLen =
            typeof block.arguments === "string"
              ? block.arguments.length
              : JSON.stringify(block.arguments || block.function?.arguments || {}).length;
          tokens += Math.ceil((nameLen + argsLen) / CHARS_PER_TOKEN) + BLOCK_OVERHEAD;
        } else {
          tokens += Math.ceil(JSON.stringify(block).length / CHARS_PER_TOKEN) + BLOCK_OVERHEAD;
        }
      }
    }
    return tokens;
  }

  return Math.ceil(JSON.stringify(content).length / CHARS_PER_TOKEN);
}

/**
 * Heuristically price a single conversation message (role + content + tool calls + thinking).
 */
export function estimateMessage(message: {
  role?: string;
  content?: any;
  thinking?: string;
  tool_calls?: any[];
  attachments?: any[];
}): number {
  let tokens = ROLE_OVERHEAD;

  if (message.content) {
    tokens += estimateContentBlocks(message.content);
  }

  if (message.thinking) {
    tokens += Math.ceil(message.thinking.length / CHARS_PER_TOKEN) + BLOCK_OVERHEAD;
  }

  if (message.tool_calls && Array.isArray(message.tool_calls)) {
    for (const tc of message.tool_calls) {
      const name = tc.name || tc.function?.name || "";
      const rawArgs = tc.arguments ?? tc.function?.arguments ?? {};
      const args = typeof rawArgs === "string" ? rawArgs : JSON.stringify(rawArgs);
      tokens += Math.ceil((name.length + args.length) / CHARS_PER_TOKEN) + BLOCK_OVERHEAD;
    }
  }

  if (message.attachments && Array.isArray(message.attachments)) {
    for (const att of message.attachments) {
      if (att.type === "image") tokens += 1600;
      else if (att.type === "video") tokens += 3200;
      else tokens += estimateTextTokens(att.textContent || att.name || att.path || "");
    }
  }

  return tokens;
}

/**
 * Calculate the context breakdown for an agent session.
 */
export function calculateContextBreakdown(params: {
  systemPrompt?: string;
  tools?: readonly any[];
  messages?: readonly any[];
}): ContextBreakdownProjection {
  const systemTokens = estimateSystemPromptTokens(params.systemPrompt);
  const toolsTokens = estimateToolsTokens(params.tools);

  let messageTokens = 0;
  if (params.messages && Array.isArray(params.messages)) {
    for (const msg of params.messages) {
      messageTokens += estimateMessage(msg);
    }
  }

  return {
    systemTokens,
    toolsTokens,
    messageTokens,
    totalHeuristicTokens: systemTokens + toolsTokens + messageTokens,
  };
}

/**
 * Resolve bounded display occupancy from independently updated pressure fields.
 * Matches contextOccupancy in DeepSeek Harness.
 */
export function calculateContextOccupancy(
  pressure: ContextPressureProjection | undefined,
  fallbackUsedTokens?: number,
  fallbackContextWindow = 1_048_576
): ContextOccupancy {
  const windowCapacity = pressure?.contextWindow || fallbackContextWindow;
  const usedTokens = pressure?.projectedTokens ?? pressure?.pressureTokens ?? fallbackUsedTokens ?? 0;
  const clampedTokens = Math.max(0, usedTokens);
  const percent = Math.min(100, Math.round((clampedTokens / windowCapacity) * 100));

  return {
    percent,
    usedTokens: clampedTokens,
    contextWindow: windowCapacity,
    availableTokens: Math.max(0, windowCapacity - clampedTokens),
  };
}

/**
 * Accumulate session-wide durable token usage.
 */
export function accumulateSessionUsage(
  prevTotals: TokenUsageProjection,
  newUsage: NormalizedTokenUsage
): TokenUsageProjection {
  return {
    uncachedInputTokens: prevTotals.uncachedInputTokens + newUsage.inputTokens,
    outputTokens: prevTotals.outputTokens + newUsage.outputTokens,
    cacheReadTokens: prevTotals.cacheReadTokens + (newUsage.cacheReadTokens ?? 0),
    cacheWriteTokens: prevTotals.cacheWriteTokens + (newUsage.cacheWriteTokens ?? 0),
    totalTokens: prevTotals.totalTokens + newUsage.totalTokens,
    reasoningTokens: prevTotals.reasoningTokens + (newUsage.reasoningTokens ?? 0),
  };
}
