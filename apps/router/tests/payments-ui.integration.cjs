// Run with Electron against the isolated local fixture, never production.
const { app, BrowserWindow } = require("electron");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
app.setPath("userData", process.argv[2]);
async function main() {
  await app.whenReady();
  const win = new BrowserWindow({ show: false, width: 1440, height: 1100, webPreferences: { contextIsolation: true, sandbox: true, offscreen: true } });
  const js = code => win.webContents.executeJavaScript(code);
  const wait = async code => {
    for (let i = 0; i < 100; i++) { if (await js(code)) return; await new Promise(resolve => setTimeout(resolve, 100)); }
    throw new Error("Timed out: " + code);
  };
  const capture = async name => {
    const directory = process.env.ROUTER_PAYMENT_SCREENSHOTS;
    if (!directory) return;
    await fs.mkdir(directory, { recursive: true });
    await new Promise(resolve => setTimeout(resolve, 300));
    await fs.writeFile(path.join(directory, name + ".png"), (await win.webContents.capturePage()).toPNG());
  };
  const overflow = () => js(`document.documentElement.scrollWidth <= innerWidth && Array.from(document.querySelectorAll('main input, main button, main article')).every(el => el.getBoundingClientRect().right <= innerWidth + 1)`);
  await win.loadURL("http://127.0.0.1:5192/credits");
  await wait(`Boolean(document.querySelector('#credit-usd'))`);
  assert.equal(await js(`document.querySelector('#credit-usd').value`), "10");
  assert.equal(await js(`document.querySelector('button[type=submit]').disabled`), false);
  assert.deepEqual(await js(`Array.from(document.querySelectorAll('form button')).map(button => button.textContent.trim()).filter(label => label.startsWith('$'))`), ["$1", "$5", "$10", "$25"]);
  assert.equal(await js(`document.querySelector('aside').innerText.includes('Available credit') || document.querySelector('aside').innerText.includes('Add credit with QRIS')`), false);
  assert.equal(await js(`document.querySelector('aside').innerText.includes('Documentation')`), true);
  assert.equal(await overflow(), true);
  await capture("credits-desktop");
  await js(`window.__setCredit = value => { const input = document.querySelector('#credit-usd'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, value); input.dispatchEvent(new Event('input', { bubbles: true })); }; true`);
  for (const invalid of ["0", "0.99", "501", "1.001", "1e2"]) {
    await js(`window.__setCredit('${invalid}')`);
    await wait(`document.querySelector('button[type=submit]').disabled`);
  }
  await js(`Array.from(document.querySelectorAll('form button')).find(button => button.textContent === '$1').click()`);
  await wait(`document.querySelector('#credit-usd').value === '1' && !document.querySelector('button[type=submit]').disabled`);
  assert.match(await js(`document.querySelector('#add-credit-heading').closest('section').innerText`), /17[.]000/);
  win.setSize(320, 1000);
  await wait(`innerWidth === 320`);
  assert.equal(await overflow(), true);
  assert.match(await js(`document.querySelector('#add-credit-heading').closest('section').innerText`), /Daily reference rate.*2026-11-04/);
  await js(`document.querySelector('#add-credit-heading').scrollIntoView({ block: 'start' })`);
  await capture("credits-reference-mobile");
  win.setSize(1440, 1100);
  await wait(`innerWidth === 1440`);
  await js(`window.__setCredit('12.50')`);
  await wait(`!document.querySelector('button[type=submit]').disabled`);
  assert.match(await js(`document.querySelector('#add-credit-heading').closest('section').innerText`), /212[.]500/);
  await js(`Array.from(document.querySelectorAll('button')).find(el => el.textContent === '$25').click()`);
  await wait(`document.querySelector('#credit-usd').value === '25'`);
  assert.match(await js(`document.querySelector('#add-credit-heading').closest('section').innerText`), /425[.]000/);
  await js(`document.querySelector('form').requestSubmit()`);
  await wait(`document.body.innerText.includes('Your checkout is ready')`);
  assert.equal(await js(`window.__routerFixture.mutations.filter(item => item.name === 'router/payments:createPayment').length`), 1);
  assert.equal(await js(`window.__routerFixture.mutations.at(-1).args.creditCents`), 2500);
  await js(`document.querySelector('form').requestSubmit()`);
  assert.equal(await js(`window.__routerFixture.mutations.filter(item => item.name === 'router/payments:createPayment').length`), 1);
  assert.equal(await js(`document.querySelector('a[href="https://pay.sumopod.com/pay/fixture"]').target`), "_blank");
  await capture("credits-pending-desktop");
  win.setSize(390, 1000);
  await wait(`innerWidth === 390`);
  assert.equal(await overflow(), true);
  await capture("credits-mobile-overview");
  await js(`document.querySelector('#add-credit-heading').scrollIntoView({ block: 'start' })`);
  await capture("credits-mobile");
  win.setSize(320, 900);
  await wait(`innerWidth === 320`);
  assert.equal(await overflow(), true);
  await js(`document.querySelector('#add-credit-heading').scrollIntoView({ block: 'start' })`);
  await capture("credits-mobile-320");
  await js(`window.__routerFixture.setPaymentState('elapsed')`);
  await wait(`document.body.innerText.includes('This checkout has expired')`);
  assert.equal(await js(`document.querySelectorAll('a[href="https://pay.sumopod.com/pay/fixture"]').length`), 0);
  await js(`document.querySelector('#add-credit-heading').closest('section').querySelector('[role=status]').scrollIntoView({ block: 'center' })`);
  await capture("credits-expired-mobile");
  await js(`window.__routerFixture.setPaymentState('failed')`);
  await wait(`document.body.innerText.includes('This payment failed')`);
  assert.equal(await js(`document.body.innerText.includes('Your checkout is ready')`), false);
  await js(`window.__routerFixture.setPaymentState('completed')`);
  await wait(`document.body.innerText.includes('Payment verified. Your credit has been added.')`);
  await win.loadURL("http://127.0.0.1:5192/credits?state=recent-payments");
  await wait(`Boolean(document.querySelector('[aria-labelledby="recent-payments-heading"]'))`);
  assert.equal(await js(`document.querySelectorAll('[aria-labelledby="recent-payments-heading"] a').length`), 1);
  assert.equal(await js(`document.querySelector('[aria-label="Payment CONST-history-pending"] a').href`), 'https://checkout.pymnt.app/payment-links/history-pending');
  assert.equal(await js(`document.querySelector('[aria-label="Payment CONST-history-pending"] a').target`), '_blank');
  for (const [status, label] of [['pending', 'Awaiting payment'], ['completed', 'Paid · credited'], ['expired', 'Expired'], ['failed', 'Payment failed'], ['creating', 'Needs review']]) {
    assert.equal(await js(`document.querySelector('[aria-label="Payment CONST-history-${status}"]').innerText.includes('${label}')`), true);
  }
  assert.equal(await js(`window.__routerFixture.mutations.length`), 0);
  win.webContents.reload();
  await wait(`Boolean(document.querySelector('[aria-label="Continue payment for $1.00 credit"]'))`);
  assert.equal(await js(`window.__routerFixture.mutations.length`), 0);
  assert.equal(await overflow(), true);
  await js(`document.querySelector('#recent-payments-heading').scrollIntoView({ block: 'start' })`);
  await capture("credits-recent-mobile-320");
  win.setSize(1440, 1100);
  await wait(`innerWidth === 1440`);
  await js(`document.querySelector('#recent-payments-heading').scrollIntoView({ block: 'start' })`);
  await capture("credits-recent-desktop");
  await js(`document.querySelector('[aria-label="Hide payment CONST-history-pending"]').click()`);
  await wait(`!document.querySelector('[aria-label="Payment CONST-history-pending"]')`);
  await js(`Array.from(document.querySelectorAll('#recent-payments-heading + * button, [aria-labelledby="recent-payments-heading"] button')).find(el => el.textContent === 'Hidden payments').click()`);
  await wait(`Boolean(document.querySelector('[aria-label="Restore payment CONST-history-pending"]'))`);
  assert.equal(await js(`document.querySelectorAll('[aria-labelledby="recent-payments-heading"] a').length`), 0);
  assert.match(await js(`document.querySelector('[aria-labelledby="recent-payments-heading"]').innerText`), /does not cancel/);
  win.setSize(320, 900);
  await wait(`innerWidth === 320`);
  assert.equal(await overflow(), true);
  await new Promise(resolve => setTimeout(resolve, 350));
  await js(`const heading = document.querySelector('#recent-payments-heading'); const viewport = heading.closest('[data-radix-scroll-area-viewport]'); viewport.scrollTo({top: viewport.scrollTop + heading.getBoundingClientRect().top - viewport.getBoundingClientRect().top, behavior: 'instant'}); true`);
  await wait(`document.querySelector('#recent-payments-heading').getBoundingClientRect().top >= 60`);
  await capture("credits-hidden-mobile");
  await js(`document.querySelector('[aria-label="Restore payment CONST-history-pending"]').click()`);
  await wait(`document.body.innerText.includes('No hidden payments.')`);
  await js(`Array.from(document.querySelectorAll('[aria-labelledby="recent-payments-heading"] button')).find(el => el.textContent === 'Back to recent payments').click()`);
  await wait(`Boolean(document.querySelector('[aria-label="Continue payment for $1.00 credit"]'))`);
  assert.equal(await js(`window.__routerFixture.mutations.filter(item => item.name === 'router/payments:createPayment').length`), 0);
  assert.deepEqual(await js(`window.__routerFixture.mutations.map(item => item.args.hidden)`), [true, false]);
  await win.loadURL("http://127.0.0.1:5192/credits?state=archive-error");
  await wait(`Boolean(document.querySelector('[aria-label="Hide payment CONST-history-pending"]'))`);
  await js(`document.querySelector('[aria-label="Hide payment CONST-history-pending"]').click()`);
  await wait(`document.querySelector('[aria-labelledby="recent-payments-heading"]').innerText.includes('Could not update this payment')`);
  assert.equal(await js(`Boolean(document.querySelector('[aria-label="Payment CONST-history-pending"] a'))`), true);
  win.setSize(320, 900);
  await wait(`innerWidth === 320`);
  await win.loadURL("http://127.0.0.1:5192/credits?state=checkout-error");
  await wait(`Boolean(document.querySelector('#credit-usd'))`);
  await js(`document.querySelector('form').requestSubmit()`);
  await wait(`Boolean(document.querySelector('section [role=alert]'))`);
  assert.equal(await overflow(), true);
  await js(`document.querySelector('section [role=alert]').scrollIntoView({ block: 'center' })`);
  await capture("credits-checkout-error-mobile");
  await win.loadURL("http://127.0.0.1:5192/credits?state=unavailable");
  await wait(`document.body.innerText.includes('QRIS checkout is temporarily unavailable')`);
  assert.equal(await js(`document.querySelector('button[type=submit]').disabled`), true);
  await js(`document.querySelector('#add-credit-heading').closest('section').querySelector('[role=status]').scrollIntoView({ block: 'center' })`);
  await capture("credits-unavailable-mobile");
  await win.loadURL("http://127.0.0.1:5192/credits?state=checkout-unavailable");
  await wait(`document.body.innerText.includes('QRIS checkout could not be loaded')`);
  assert.equal(await js(`document.body.innerText.includes('Transaction history') && document.body.innerText.includes('Available credit')`), true);
  assert.equal(await js(`document.body.innerText.includes('Credits could not be loaded')`), false);
  await win.loadURL("http://127.0.0.1:5192/models");
  await wait(`document.body.innerText.includes('Models & pricing')`);
  assert.equal(await js(`document.body.innerText.includes(':free') || document.body.innerText.includes('Weekly free allowance')`), false);
  assert.equal(await overflow(), true);
  console.log("PASS: QRIS summary, preset selection, checkout creation, pending link, disabled configuration, error recovery, and desktop/390px/320px layouts");
  win.destroy();
}
main().then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1); });
